
  CREATE OR REPLACE EDITIONABLE PACKAGE BODY "ADMIN"."PKG_PELICULAS_G8" AS

    PROCEDURE LISTAR_PELICULAS(
        P_RESULTADO OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT ID_PELICULA,
                   TITULO,
                   DURACION,
                   CLASIFICACION,
                   ESTADO
            FROM PELICULA_TB
            ORDER BY TITULO;
    END LISTAR_PELICULAS;

    PROCEDURE BUSCAR_PELICULA(
        P_ID_PELICULA IN NUMBER,
        P_RESULTADO OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT ID_PELICULA,
                   TITULO,
                   DURACION,
                   CLASIFICACION,
                   ESTADO
            FROM PELICULA_TB
            WHERE ID_PELICULA = P_ID_PELICULA;
    END BUSCAR_PELICULA;

END PKG_PELICULAS_G8;
