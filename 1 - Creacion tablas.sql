        REFERENCES CATEGORIAALIMENTO_TB (ID_CATEGORIA),
    CONSTRAINT CK_ALIMENTO_DISPONIBLE    CHECK (DISPONIBLE IN (0, 1)),
    CONSTRAINT CK_ALIMENTO_PRECIO CHECK (PRECIO >= 0)
