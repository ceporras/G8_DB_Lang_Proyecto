
  CREATE OR REPLACE EDITIONABLE PACKAGE "ADMIN"."PKG_PROMOCIONES_G8" AS

    PROCEDURE LISTAR_PROMOCIONES(
        P_RESULTADO OUT SYS_REFCURSOR
    );

    PROCEDURE BUSCAR_PROMOCION(
        P_ID IN NUMBER,
        P_RESULTADO OUT SYS_REFCURSOR
    );

    FUNCTION VALIDAR_CODIGO(
        P_CODIGO IN VARCHAR2
    ) RETURN NUMBER;

END PKG_PROMOCIONES_G8;

CREATE OR REPLACE EDITIONABLE PACKAGE BODY "ADMIN"."PKG_PROMOCIONES_G8" AS

    PROCEDURE LISTAR_PROMOCIONES(
        P_RESULTADO OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT *
            FROM PROMOCION_TB
            ORDER BY ID_PROMOCION;
    END LISTAR_PROMOCIONES;

    PROCEDURE BUSCAR_PROMOCION(
        P_ID IN NUMBER,
        P_RESULTADO OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT *
            FROM PROMOCION_TB
            WHERE ID_PROMOCION = P_ID;
    END BUSCAR_PROMOCION;

    FUNCTION VALIDAR_CODIGO(
        P_CODIGO IN VARCHAR2
    ) RETURN NUMBER
    AS
        V_TOTAL NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO V_TOTAL
        FROM PROMOCION_TB
        WHERE CODIGO = P_CODIGO
          AND ESTADO = 1
          AND (FECHAINICIO IS NULL
               OR FECHAINICIO <= SYSTIMESTAMP)
          AND (FECHAFIN IS NULL
               OR FECHAFIN >= SYSTIMESTAMP);

        IF V_TOTAL > 0 THEN
            RETURN 1;
        ELSE
            RETURN 0;
        END IF;
    END VALIDAR_CODIGO;

END PKG_PROMOCIONES_G8;
