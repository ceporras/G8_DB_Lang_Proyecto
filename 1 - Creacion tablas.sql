CREATE TABLE COMPRAALIMENTO_TB (
    ID_COMPRAALIMENTO NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    ID_ORDEN          NUMBER(10) NOT NULL,
    ID_ALIMENTO       NUMBER(10) NOT NULL,
    CANTIDAD          NUMBER(5) NOT NULL,
    PRECIOUNITARIO    NUMBER(10,2) NOT NULL,
    CONSTRAINT PK_COMPRA_ALIMENTO PRIMARY KEY (ID_COMPRAALIMENTO),
    CONSTRAINT FK_CA_ORDEN FOREIGN KEY (ID_ORDEN)
        REFERENCES ORDEN_TB (ID_ORDEN),
    CONSTRAINT FK_CA_ALIMENTO FOREIGN KEY (ID_ALIMENTO)
        REFERENCES ALIMENTO_TB (ID_ALIMENTO),
    CONSTRAINT CK_CA_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_CA_PRECIO CHECK (PRECIOUNITARIO >= 0),
    CONSTRAINT UQ_CA_ORDEN_ALIMENTO UNIQUE (ID_ORDEN, ID_ALIMENTO)
);
