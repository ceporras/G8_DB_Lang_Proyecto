CREATE TABLE CINE_TB (
    ID_CINE         NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    NOMBRE          VARCHAR2(100) NOT NULL,
    DIRECCION       VARCHAR2(250),
    TELEFONO        VARCHAR2(30),
    ESTADO          NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_CINE PRIMARY KEY (ID_CINE),
    CONSTRAINT CK_CINE_ESTADO    CHECK (ESTADO IN (0, 1)),
    CONSTRAINT UQ_CINE_NOMBRE UNIQUE (NOMBRE)
);


CREATE TABLE GENERO_TB (
    ID_GENERO       NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    NOMBRE          VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_GENERO PRIMARY KEY (ID_GENERO),
    CONSTRAINT UQ_GENERO_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE PELICULA_TB (
    ID_PELICULA     NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    TITULO          VARCHAR2(200) NOT NULL,
    SINOPSIS        VARCHAR2(2000),
    DURACION        NUMBER(4) DEFAULT 0 NOT NULL, -- minutes
    CLASIFICACION   VARCHAR2(20) NOT NULL,
    FECHAESTRENO    DATE NOT NULL,
    URLTRAILER      VARCHAR2(2000),
    URLPOSTER       VARCHAR2(2000),
    ESTADO          NUMBER(1) DEFAULT 1 NOT NULL,
    IDIOMA          VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_PELICULA PRIMARY KEY (ID_PELICULA),
    CONSTRAINT CK_PELICULA_ESTADO    CHECK (ESTADO IN (0, 1)),
    CONSTRAINT CK_PELICULA_DURACION CHECK (DURACION > 0)
);

CREATE TABLE PELICULA_GENERO_TB (
    ID_PELICULA     NUMBER(10) NOT NULL,
    ID_GENERO       NUMBER(10) NOT NULL,
    CONSTRAINT PK_PELICULA_GENERO PRIMARY KEY (ID_PELICULA, ID_GENERO),
    CONSTRAINT FK_PG_PELICULA FOREIGN KEY (ID_PELICULA)
        REFERENCES PELICULA_TB (ID_PELICULA) ON DELETE CASCADE,
    CONSTRAINT FK_PG_GENERO FOREIGN KEY (ID_GENERO)
        REFERENCES GENERO_TB (ID_GENERO) ON DELETE CASCADE
);

CREATE TABLE SALA_TB (
    ID_SALA        NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    ID_CINE        NUMBER(10) NOT NULL,
    NOMBRE         VARCHAR2(50) NOT NULL,
    CAPACIDAD      NUMBER(5) DEFAULT 0 NOT NULL,
    TIPOPANTALLA   VARCHAR2(45) NOT NULL,
    CONSTRAINT PK_SALA PRIMARY KEY (ID_SALA),
    CONSTRAINT FK_SALA_CINE FOREIGN KEY (ID_CINE)
        REFERENCES CINE_TB (ID_CINE),
    CONSTRAINT CK_SALA_CAPACIDAD CHECK (CAPACIDAD > 0),
    CONSTRAINT UQ_SALA_CINE_NOMBRE UNIQUE (ID_CINE, NOMBRE)
);

CREATE TABLE ASIENTO_TB (
    ID_ASIENTO     NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    ID_SALA        NUMBER(10) NOT NULL,
    FILA           VARCHAR2(10) NOT NULL,
    NUMERO         NUMBER(4) NOT NULL,
    TIPOASIENTO    VARCHAR2(45) DEFAULT 'Estandar' NOT NULL,
    CONSTRAINT PK_ASIENTO PRIMARY KEY (ID_ASIENTO),
    CONSTRAINT FK_ASIENTO_SALA FOREIGN KEY (ID_SALA)
        REFERENCES SALA_TB (ID_SALA) ON DELETE CASCADE,
    CONSTRAINT UQ_ASIENTO_SALA_POS UNIQUE (ID_SALA, FILA, NUMERO),
    CONSTRAINT CK_ASIENTO_NUMERO CHECK (NUMERO > 0)
);

CREATE TABLE FUNCION_TB (
    ID_FUNCION     NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    ID_PELICULA    NUMBER(10) NOT NULL,
    ID_SALA        NUMBER(10) NOT NULL,
    HORAINICIO     TIMESTAMP NOT NULL,
    HORAFIN        TIMESTAMP NOT NULL,
    IDIOMA         VARCHAR2(50),
    FORMATO        VARCHAR2(30),
    CONSTRAINT PK_FUNCION PRIMARY KEY (ID_FUNCION),
    CONSTRAINT FK_FUNC_PELICULA FOREIGN KEY (ID_PELICULA)
        REFERENCES PELICULA_TB (ID_PELICULA),
    CONSTRAINT FK_FUNC_SALA FOREIGN KEY (ID_SALA)
        REFERENCES SALA_TB (ID_SALA),
    CONSTRAINT CK_FUNC_HORAS CHECK (HORAFIN > HORAINICIO)
);

CREATE TABLE PROMOCION_TB (
    ID_PROMOCION           NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    CODIGO                 VARCHAR2(45),
    NOMBRE                 VARCHAR2(100) NOT NULL,
    PORCENTAJEDESCUENTO    NUMBER(5,2) DEFAULT 0 NOT NULL,
    FECHAINICIO            TIMESTAMP,
    FECHAFIN               TIMESTAMP,
    ESTADO                 NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_PROMOCION PRIMARY KEY (ID_PROMOCION),
    CONSTRAINT UQ_PROMOCION_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_PROMO_ESTADO    CHECK (ESTADO IN (0, 1)),
    --descuento no puede ser mas de 100 como es porcentaje
    CONSTRAINT CK_PROMO_DESCUENTO CHECK
        (PORCENTAJEDESCUENTO BETWEEN 0 AND 100),
    CONSTRAINT CK_PROMO_FECHAS CHECK
        (FECHAFIN IS NULL OR FECHAINICIO IS NULL OR FECHAFIN >= FECHAINICIO)
);

CREATE TABLE CLIENTE_TB (
    ID_CLIENTE       NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    NOMBRE           VARCHAR2(60) NOT NULL,
    APELLIDOPATERNO  VARCHAR2(60) NOT NULL,
    APELLIDOMATERNO  VARCHAR2(60),
    CORREO           VARCHAR2(254) NOT NULL,
    TELEFONO         VARCHAR2(30),
    FECHAREGISTRO    DATE DEFAULT SYSDATE NOT NULL,
    CONTRASENNA     VARCHAR2(255),
    CONSTRAINT PK_CLIENTE PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UQ_CLIENTE_CORREO UNIQUE (CORREO)
);


CREATE TABLE ORDEN_TB (
    ID_ORDEN       NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    ID_CLIENTE     NUMBER(10) NOT NULL,
    ID_PROMOCION   NUMBER(10),
    FECHAORDEN     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ESTADO         VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    SUBTOTAL       NUMBER(10,2) DEFAULT 0 NOT NULL,
    DESCUENTO      NUMBER(10,2) DEFAULT 0 NOT NULL,
    TOTAL          NUMBER(10,2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ORDEN PRIMARY KEY (ID_ORDEN),
    CONSTRAINT FK_ORDEN_CLIENTE FOREIGN KEY (ID_CLIENTE)
        REFERENCES CLIENTE_TB (ID_CLIENTE),
    CONSTRAINT FK_ORDEN_PROMOCION FOREIGN KEY (ID_PROMOCION)
        REFERENCES PROMOCION_TB (ID_PROMOCION),
    CONSTRAINT CK_ORDEN_MONTOS CHECK
        (SUBTOTAL >= 0 AND DESCUENTO >= 0 AND TOTAL >= 0)
);

CREATE TABLE BOLETO_TB (
    ID_BOLETO       NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    ID_ORDEN        NUMBER(10) NOT NULL,
    ID_FUNCION      NUMBER(10) NOT NULL,
    ID_ASIENTO      NUMBER(10) NOT NULL,
    TIPOBOLETO      VARCHAR2(45) NOT NULL,
    PRECIO          NUMBER(10,2) NOT NULL,
    CONSTRAINT PK_BOLETO PRIMARY KEY (ID_BOLETO),
    CONSTRAINT FK_BOLETO_ORDEN FOREIGN KEY (ID_ORDEN)
        REFERENCES ORDEN_TB (ID_ORDEN),
    CONSTRAINT FK_BOLETO_FUNCION FOREIGN KEY (ID_FUNCION)
        REFERENCES FUNCION_TB (ID_FUNCION),
    CONSTRAINT FK_BOLETO_ASIENTO FOREIGN KEY (ID_ASIENTO)
        REFERENCES ASIENTO_TB (ID_ASIENTO),
    -- combinacion de funcion y asiento son UQ para evitar vender 2 veces el mismo asiento
    CONSTRAINT UQ_BOLETO_FUNCION_ASIENTO UNIQUE (ID_FUNCION, ID_ASIENTO),
    CONSTRAINT CK_BOLETO_PRECIO CHECK (PRECIO >= 0)
);

CREATE TABLE PAGO_TB (
    ID_PAGO                NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    ID_ORDEN               NUMBER(10) NOT NULL,
    MONTO                  NUMBER(10,2) NOT NULL,
    FECHAPAGO              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    METODOPAGO             VARCHAR2(45),
    REFERENCIATRANSACCION  VARCHAR2(150),
    ESTADO                 NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_PAGO PRIMARY KEY (ID_PAGO),
    CONSTRAINT FK_PAGO_ORDEN FOREIGN KEY (ID_ORDEN)
        REFERENCES ORDEN_TB (ID_ORDEN),
    CONSTRAINT CK_PAGO_MONTO CHECK (MONTO > 0),
    CONSTRAINT CK_ESTADO    CHECK (ESTADO IN (0, 1)),
    CONSTRAINT UQ_PAGO_REFERENCIA UNIQUE (REFERENCIATRANSACCION)
);

CREATE TABLE CATEGORIAALIMENTO_TB (
    ID_CATEGORIA    NUMBER(10) GENERATED ALWAYS AS IDENTITY,
    NOMBRE          VARCHAR2(60) NOT NULL,
    CONSTRAINT PK_CATEGORIA_ALIMENTO PRIMARY KEY (ID_CATEGORIA),
