
  CREATE OR REPLACE EDITIONABLE TRIGGER "ADMIN"."TRG_VALIDAR_SALA_BOLETO_G8" 
BEFORE INSERT OR UPDATE OF ID_FUNCION, ID_ASIENTO
ON BOLETO_TB
FOR EACH ROW
DECLARE
    V_SALA_FUNCION NUMBER;
    V_SALA_ASIENTO NUMBER;
BEGIN

    SELECT ID_SALA
    INTO V_SALA_FUNCION
    FROM FUNCION_TB
    WHERE ID_FUNCION = :NEW.ID_FUNCION;

    SELECT ID_SALA
    INTO V_SALA_ASIENTO
    FROM ASIENTO_TB
    WHERE ID_ASIENTO = :NEW.ID_ASIENTO;

    IF V_SALA_FUNCION <> V_SALA_ASIENTO THEN
        RAISE_APPLICATION_ERROR(
            -20002,
            'El asiento no pertenece a la sala de la funcion'
        );
    END IF;

END;

ALTER TRIGGER "ADMIN"."TRG_VALIDAR_SALA_BOLETO_G8" ENABLE