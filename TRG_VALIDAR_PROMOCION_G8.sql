
  CREATE OR REPLACE EDITIONABLE TRIGGER "ADMIN"."TRG_VALIDAR_PROMOCION_G8" 
BEFORE INSERT OR UPDATE OF PORCENTAJEDESCUENTO
ON PROMOCION_TB
FOR EACH ROW
BEGIN
    IF :NEW.PORCENTAJEDESCUENTO < 0
       OR :NEW.PORCENTAJEDESCUENTO > 100 THEN

        RAISE_APPLICATION_ERROR(
            -20001,
            'El descuento debe estar entre 0 y 100'
        );

    END IF;
END;

ALTER TRIGGER "ADMIN"."TRG_VALIDAR_PROMOCION_G8" ENABLE